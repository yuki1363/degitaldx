// 日本語の表記ゆれ正規化（NFKC）。
//   ・半角カタカナ → 全角カタカナ（ﾌｨﾙﾑ → フィルム）
//   ・全角英数 → 半角英数（ＫＥＮ１２３ → KEN123）
//   ・全角スペース → 半角、その他の互換文字（㈱→(株) 等）も正規化する
//
// 目的: 設備名・部品名などのマスタ表記を統一し、検索と一覧表示のゆれを無くす。
//   保存時（設備・部品の作成/更新/取込）と、管理画面の一括正規化で共通利用する。
//   ※ NFKC は冪等（何度かけても結果は同じ）なので、既存データへの再適用も安全。
export function normalizeJa(s) {
  if (s == null) return s;
  return String(s).normalize('NFKC');
}

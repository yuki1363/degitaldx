const norm = (s) => String(s || '').normalize('NFKC').toLowerCase();

function buildSection(sec) {
  const d = el('details', { class: 'help-sec', id: sec.id, 'data-search': norm(`${sec.title} ${sec.items.join(' ')}`) }, [
    el('summary', { class: 'help-sum' }, `${sec.icon} ${sec.title}`),
    el('ul', { class: 'help-list' }, sec.items.map((t) => el('li', {}, t))),
  ]);
  return d;
}

const app = document.getElementById('app');
const secs = HELP.map(buildSection);
const note = el('p', { class: 'hint help-note' }, '');
const search = el('input', { type: 'search', class: 'help-search', placeholder: '知りたい言葉で探す（例: 送信待ち、QR、印刷）', 'aria-label': 'ガイドを検索' });
search.addEventListener('input', () => {
  const q = norm(search.value).trim();
  let shown = 0;
  for (const d of secs) {
    const hit = !q || q.split(/\s+/).every((w) => d.dataset.search.includes(w));
    d.hidden = !hit;
    if (q && hit && !d.open) { d.open = true; d.dataset.auto = '1'; }  // 検索中は該当の項目を開く
    if (!q && d.dataset.auto) { d.open = false; delete d.dataset.auto; } // 検索を消したら、検索で開いたものを閉じる
    if (hit) shown++;
  }
  note.textContent = q && shown === 0 ? '該当する項目がありません。別の言葉で探してみてください。' : '';
});

render(app, [
  el('div', { class: 'card' }, [
    el('p', { class: 'hint' }, '機能ごとの使い方です。項目をタップすると開きます。'),
    search, note,
  ]),
  el('div', { class: 'help-body' }, secs),
]);

// /pages/help#parts のように項目を指定して開く（ページ内でハッシュだけ変わった場合も反映する）
function openFromHash() {
  const target = decodeURIComponent((location.hash || '').slice(1));
  const hit = secs.find((d) => d.id === target);
  if (hit) { hit.hidden = false; hit.open = true; hit.scrollIntoView(); }
}
window.addEventListener('hashchange', openFromHash);
openFromHash();
